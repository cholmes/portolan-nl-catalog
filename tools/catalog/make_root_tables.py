def load(rel):
    p = CATALOG / rel / "collection.json"
    return json.loads(p.read_text()) if p.exists() else None


def members(rel):
    """Collections under rel: itself, or every collection in the subtree."""
    direct = load(rel)
    if direct:
        return [direct]
    return [json.loads(p.read_text())
            for p in sorted((CATALOG / rel).rglob("collection.json"))]


def fmt_count(n):
    if n is None:
        return "—"
    if n >= 1_000_000:
        return f"{n / 1_000_000:.1f}M"
    return f"{n:,}"


def row(title, rel, blurb):
    docs = members(rel)
    counts = [d.get("table:row_count") for d in docs]
    total = sum(c for c in counts if c) or None
    geoms = sorted({g for d in docs
                    for g in (d.get("summaries", {}).get("vector:geometry_types") or [])})
    if rel == "beeldmateriaal/luchtfoto_2024":
        total_s = f"{total} scenes" if total else "—"
        geom_s, fmt = "Raster", "COG"
    else:
        total_s = fmt_count(total)
        geom_s = geoms[0] if len(geoms) == 1 else (", ".join(geoms) or "—")
        fmt = "GeoParquet, PMTiles"
    provider = PROVIDER_SHORT[rel.split("/")[0]]
    return f"| [{title}](./{rel}/) | {provider} | {total_s} | {geom_s} | {fmt} | {blurb} |"


def providers_table():
    out = ["| Institution | Description | Collections |", "|---|---|---|"]
    for d, (disp, blurb) in PROVIDERS.items():
        n = len(list((CATALOG / d).rglob("collection.json")))
        out.append(f"| {disp} | {blurb} | {n} |")
    return "\n".join(out)


def collections_table():
    out = ["| Collection | Provider | Features | Geometry | Format | Description |",
           "|---|---|---|---|---|---|"]
    out += [row(*r) for r in ROWS]
    return "\n".join(out)


def replace_block(text, name, body):
    begin = f"<!-- generated:{name} -->"
    end = "<!-- /generated -->"
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    block = f"{begin}\n{BEGIN}\n{body}\n{END}\n{end}"
    if not pattern.search(text):
        raise SystemExit(f"marker 'generated:{name}' not found")
    return pattern.sub(block, text)


def agents_listing():
    out = []
    for d, (disp, blurb) in PROVIDERS.items():
        title = re.sub(r"\*\*\[(.*?)\].*", r"\1", disp)
        out.append(f"### {title} ({blurb})")
        for row_title, rel, row_blurb in ROWS:
            if not rel.startswith(d + "/"):
                continue
            docs = members(rel)
            total = sum(c for c in (x.get("table:row_count") for x in docs) if c) or None
            if rel == "beeldmateriaal/luchtfoto_2024":
                count = f"{total} scenes"
            else:
                count = f"{fmt_count(total)} features" if total else "feature count in metadata"
            name = rel.split("/", 1)[1]
            out.append(f"- **{name}/** — {row_blurb} ({count})")
        out.append("")
    return "\n".join(out).rstrip()


def main():
    readme = CATALOG / "README.md"
    text = readme.read_text()
    text = replace_block(text, "providers-table", providers_table())
    text = replace_block(text, "collections-table", collections_table())
    readme.write_text(text)
    print("  wrote README.md tables")
    agents = CATALOG / "AGENTS.md"
    text = agents.read_text()
    text = replace_block(text, "collections-listing", agents_listing())
    agents.write_text(text)
    print("  wrote AGENTS.md listing")


if __name__ == "__main__":
    main()
